#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Download the processed data and the projected attributable numbers of deaths in London
from the forked repository of the tutorial by Quijal-Zamorano et al.
(branch "reanalysis"); the files are generated by the R scripts of the tutorial.
"""

import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

CONFIG = {
    "BASE_URL": "https://raw.githubusercontent.com/t-yui/climate_demographic_health_projections/reanalysis/",
    "FILES": [
        "indata/processed/study_parameters.RData",
        "indata/processed/data_global_warming_levels_ssp245.RData",
        "outdata/file/03_calibrated_demographic_projections/data_proj_mort_spatialcal_tempcal_ssp2.RData",
        "outdata/file/03_calibrated_demographic_projections/attributable_number_ssp245.RData",
        "outdata/file/04_health_impacts/heat_related_mortality_gwl_ssp245.RData",
        "outdata/file/04_health_impacts/heat_related_mortality_endcentury_ssp245.RData",
        "outdata/file/04_health_impacts/heat_related_mortality_decades_ssp245.RData",
    ],
    "DATA_DIR": ROOT / "data" / "climate_demographic_health_projections",
}


def main():
    for rel in CONFIG["FILES"]:
        dest = Path(CONFIG["DATA_DIR"]) / rel
        if dest.exists():
            print(f"exists: {dest}")
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        print(f"downloading {rel}", flush=True)
        urllib.request.urlretrieve(CONFIG["BASE_URL"] + rel, dest)


if __name__ == "__main__":
    main()
